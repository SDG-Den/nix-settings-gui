#!/usr/bin/env bash
set -euo pipefail

root=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
cd "$root"
name=$(basename "$root")
namespace="services.nix-settings-gui"

out=$(nix build --impure --no-link --print-out-paths --expr "
let
  flake = builtins.getFlake (toString ./.);
  pkgs = flake.inputs.nixpkgs.legacyPackages.x86_64-linux;
  lib = pkgs.lib;
  eval = flake.inputs.nixpkgs.lib.nixosSystem {
    system = \"x86_64-linux\";
    modules = [ flake.nixosModules.default ];
  };
  path = lib.splitString \".\" \"$namespace\";
  options = lib.setAttrByPath path (lib.getAttrFromPath path eval.options);
  doc = pkgs.nixosOptionsDoc {
    inherit options;
    transformOptions = opt: opt // { declarations = [ ]; };
  };
in doc.optionsCommonMark
" 2>/dev/null)

{
  printf '<!-- Generated by scripts/gen-options.sh. Do not edit by hand. -->\n\n'
  printf '# %s options\n\n' "$name"
  cat "$out"
} > OPTIONS.md
